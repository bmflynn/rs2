/// Copy of [GOOD] with `count` errors. Positions are 37*i mod 255. They are all different
/// for i < 255 because 37 and 255 have no common factor. Values are never zero.
fn with_errors(count: usize) -> [u8; 255] {
    let mut block = GOOD;
    for i in 0..count {
        block[(37 * i) % 255] ^= (13 * i as u8).wrapping_add(1);
    }
    block
}

fn decode(c: &mut Criterion) {
    let mut group = c.benchmark_group("decode");
    group.throughput(Throughput::Bytes(255));

    // Check the inputs once, so a wrong benchmark case fails loudly.
    assert_eq!(correct_message(&GOOD).state, RSState::Ok);
    for count in [1, 16] {
        assert_eq!(
            correct_message(&with_errors(count)).state,
            RSState::Corrected(count as i32)
        );
    }
    assert!(matches!(
        correct_message(&with_errors(17)).state,
        RSState::Uncorrectable(_)
    ));

    group.bench_function("clean", |b| {
        b.iter(|| correct_message(black_box(&GOOD)));
    });
    for count in [1, 16, 17] {
        let block = with_errors(count);
        group.bench_function(format!("errors_{count}"), |b| {
            b.iter(|| correct_message(black_box(&block)));
        });
    }
    group.finish();

    // In place version. The copy of the input is part of the measured time, because the
    // function may change the buffer. It is 255 bytes on the stack.
    let mut group = c.benchmark_group("decode_in_place");
    group.throughput(Throughput::Bytes(255));
    for (name, block) in [
        ("clean", GOOD),
        ("errors_1", with_errors(1)),
        ("errors_16", with_errors(16)),
    ] {
        group.bench_function(name, |b| {
            b.iter(|| {
                let mut buf = black_box(block);
                correct_in_place(&mut buf)
            });
        });
    }
    group.finish();
}

fn detect(c: &mut Criterion) {
    let mut group = c.benchmark_group("has_errors");
    group.throughput(Throughput::Bytes(255));

    let bad = with_errors(1);
    group.bench_function("clean", |b| {
        b.iter(|| has_errors(black_box(&GOOD)));
    });
    group.bench_function("errors_1", |b| {
        b.iter(|| has_errors(black_box(&bad)));
    });
    group.finish();
}

criterion_group!(benches, decode, detect);
criterion_main!(benches);
